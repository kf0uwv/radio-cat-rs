/// Index of the first non-zero sample of the half pulse.
fn pulse_first(half: &[f32]) -> usize {
    half.iter().position(|&x| x != 0.0).unwrap()
}

#[test]
fn tables_match_their_definitions() {
    let bits = |v: &[f32]| v.iter().map(|x| x.to_bits()).collect::<Vec<_>>();
    let half = generate_pulse_half();
    let first = pulse_first(&half);
    assert_eq!(first, tables::PULSE_FIRST);
    // Every sample left out is exactly +0.0.
    assert!(half[..first].iter().all(|x| x.to_bits() == 0));
    assert_eq!(bits(&PULSE_HALF), bits(&half[first..]));
    assert_eq!(bits(&QUARTER_SINE), bits(&generate_quarter_sine()));
}

#[test]
fn pulse_sums_to_one_per_symbol() {
    let ns = SAMPLES_PER_SYMBOL;
    for s in 0..ns {
        let sum = pulse(s) + pulse(s + ns) + pulse(s + 2 * ns);
        assert!((sum - 1.0).abs() < 1e-4, "sample {s}: {sum}");
    }
    assert!(pulse(PULSE_SAMPLES / 2) > 0.99);
    assert!(pulse(0) < 1e-3);
}

#[test]
fn table_sine_is_accurate() {
    let mut worst = 0.0f64;
    for k in 0..200_000u32 {
        let phase = k.wrapping_mul(2_147_483); // spread over the turn
        let exact = libm::sin(f64::from(phase) / 4_294_967_296.0 * 2.0 * core::f64::consts::PI);
        worst = worst.max((f64::from(sin_turns(phase)) - exact).abs());
        let exact_c = libm::cos(f64::from(phase) / 4_294_967_296.0 * 2.0 * core::f64::consts::PI);
        worst = worst.max((f64::from(cos_turns(phase)) - exact_c).abs());
    }
    assert!(worst < 4e-7, "{worst}");
    assert_eq!(sin_turns(0), 0.0);
    assert_eq!(sin_turns(1 << 30), 1.0);
    assert_eq!(sin_turns(3 << 30), -1.0);
}

