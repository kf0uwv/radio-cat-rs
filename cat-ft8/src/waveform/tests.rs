fn tables_source() -> std::string::String {
    use std::fmt::Write;
    let mut s = std::string::String::new();
    s.push_str(LICENCE_HEADER);
    s.push_str(
        "// Generated by `cargo test -p cat-ft8 --lib print_tables -- --ignored \
         --nocapture`;\n// checked bit-for-bit by `tables_match_their_definitions`. Do not edit.\n\n",
    );
    let emit = |s: &mut std::string::String, name: &str, doc: &str, v: &[f32]| {
        writeln!(s, "{doc}").unwrap();
        writeln!(s, "#[rustfmt::skip]").unwrap();
        writeln!(s, "pub(crate) static {name}: [f32; {}] = [", v.len()).unwrap();
        for chunk in v.chunks(6) {
            let line: Vec<std::string::String> =
                chunk.iter().map(|x| std::format!("{x:?}")).collect();
            writeln!(s, "    {},", line.join(", ")).unwrap();
        }
        writeln!(s, "];\n").unwrap();
    };
    let half = generate_pulse_half();
    let first = pulse_first(&half);
    emit(
        &mut s,
        "PULSE_HALF",
        "/// GFSK frequency pulse (QEX eq. 3, BT = 2), samples `PULSE_FIRST..=2880`\n\
         /// of the 5760-sample pulse; the rest mirrors about sample 2880, and the\n\
         /// samples before `PULSE_FIRST` are exactly zero.",
        &half[first..],
    );
    writeln!(
        s,
        "/// Index of the first non-zero pulse sample (the table's first entry).\n\
         pub(crate) const PULSE_FIRST: usize = {first};\n"
    )
    .unwrap();
    emit(
        &mut s,
        "QUARTER_SINE",
        "/// `sin(i · (π/2) / 1024)` for i = 0..=1024, rounded to `f32`.",
        &generate_quarter_sine(),
    );
    s.trim_end().into()
}

