#[test]
fn ramps_and_amplitude() {
    let symbols = [0u8; SYMBOL_COUNT];
    let mut out = vec![0.0; WAVEFORM_SAMPLES + 100];
    let p = Placement {
        base_hz: 1500.0,
        start: 50,
        amplitude: 0.5,
    };
    synthesize(&symbols, &p, &mut out).unwrap();
    assert!(out[..50].iter().all(|&x| x == 0.0));
    assert_eq!(out[50], 0.0); // sin(0) and zero envelope
    assert!(out[50..50 + 40].iter().all(|x| x.abs() < 0.1));
    let peak = out.iter().fold(0.0f32, |a, &x| a.max(x.abs()));
    assert!(peak <= 0.5 + 1e-6 && peak > 0.49);
    assert!(out[50 + WAVEFORM_SAMPLES..].iter().all(|&x| x == 0.0));
    assert!(out[50 + WAVEFORM_SAMPLES - 1].abs() < 1e-3);
    assert_eq!(envelope(0), 0.0);
    assert_eq!(envelope(RAMP_SAMPLES), 1.0);
    assert_eq!(envelope(WAVEFORM_SAMPLES - 1), 0.0);
}

