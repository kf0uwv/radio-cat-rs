/// The half pulse, from QEX eq. 3 with `libm`'s `erff` (the definition of
/// `tables::PULSE_HALF`).
fn generate_pulse_half() -> Vec<f32> {
    let k = core::f32::consts::PI * libm::sqrtf(2.0 / core::f32::consts::LN_2);
    let ns = SAMPLES_PER_SYMBOL as f32;
    (0..PULSE_HALF_LEN)
        .map(|i| {
            let t = (i as f32 - 1.5 * ns) / ns;
            0.5 * (libm::erff(k * BT * (t + 0.5)) - libm::erff(k * BT * (t - 0.5)))
        })
        .collect()
}

/// `sin` over a quarter turn in 1024 steps, computed in `f64` and rounded
/// to `f32` (the definition of `tables::QUARTER_SINE`).
fn generate_quarter_sine() -> Vec<f32> {
    (0..SINE_TABLE_LEN)
        .map(|i| libm::sin(i as f64 * core::f64::consts::FRAC_PI_2 / 1024.0) as f32)
        .collect()
}

