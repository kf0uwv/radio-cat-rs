fn tables_source() -> std::string::String {
    use std::fmt::Write;
    let mut s = std::string::String::new();
    s.push_str(LICENCE_HEADER);
    s.push_str(
        "// Generated by `cargo test -p cat-ft8 --lib print_tables -- --ignored \
         --nocapture`;\n// checked bit-for-bit by `tables_match_their_definitions`. Do not edit.\n\n",
    );
    let emit = |s: &mut std::string::String, name: &str, doc: &str, v: &[f32]| {
        writeln!(s, "{doc}").unwrap();
        writeln!(s, "#[rustfmt::skip]").unwrap();
        writeln!(s, "pub(crate) static {name}: [f32; {}] = [", v.len()).unwrap();
        for chunk in v.chunks(6) {
            let line: Vec<std::string::String> =
                chunk.iter().map(|x| std::format!("{x:?}")).collect();
            writeln!(s, "    {},", line.join(", ")).unwrap();
        }
        writeln!(s, "];\n").unwrap();
    };
    let half = generate_pulse_half();
    let first = pulse_first(&half);
    emit(
        &mut s,
        "PULSE_HALF",
        "/// GFSK frequency pulse (QEX eq. 3, BT = 2), samples `PULSE_FIRST..=2880`\n\
         /// of the 5760-sample pulse; the rest mirrors about sample 2880, and the\n\
         /// samples before `PULSE_FIRST` are exactly zero.",
        &half[first..],
    );
    writeln!(
        s,
        "/// Index of the first non-zero pulse sample (the table's first entry).\n\
         pub(crate) const PULSE_FIRST: usize = {first};\n"
    )
    .unwrap();
    emit(
        &mut s,
        "QUARTER_SINE",
        "/// `sin(i · (π/2) / 1024)` for i = 0..=1024, rounded to `f32`.",
        &generate_quarter_sine(),
    );
    s.trim_end().into()
}

#[test]
fn tables_file_is_exactly_the_generator_output() {
    // Line endings aside: a Windows checkout may turn `\n` into `\r\n`.
    assert_eq!(
        include_str!("tables.rs").replace("\r\n", "\n"),
        std::format!("{}\n", tables_source())
    );
}

/// Index of the first non-zero sample of the half pulse.
fn pulse_first(half: &[f32]) -> usize {
    half.iter().position(|&x| x != 0.0).unwrap()
}

#[test]
fn tables_match_their_definitions() {
    let bits = |v: &[f32]| v.iter().map(|x| x.to_bits()).collect::<Vec<_>>();
    let half = generate_pulse_half();
    let first = pulse_first(&half);
    assert_eq!(first, tables::PULSE_FIRST);
    // Every sample left out is exactly +0.0.
    assert!(half[..first].iter().all(|x| x.to_bits() == 0));
    assert_eq!(bits(&PULSE_HALF), bits(&half[first..]));
    assert_eq!(bits(&QUARTER_SINE), bits(&generate_quarter_sine()));
}

#[test]
fn pulse_sums_to_one_per_symbol() {
    let ns = SAMPLES_PER_SYMBOL;
    for s in 0..ns {
        let sum = pulse(s) + pulse(s + ns) + pulse(s + 2 * ns);
        assert!((sum - 1.0).abs() < 1e-4, "sample {s}: {sum}");
    }
    assert!(pulse(PULSE_SAMPLES / 2) > 0.99);
    assert!(pulse(0) < 1e-3);
}

#[test]
fn table_sine_is_accurate() {
    let mut worst = 0.0f64;
    for k in 0..200_000u32 {
        let phase = k.wrapping_mul(2_147_483); // spread over the turn
        let exact = libm::sin(f64::from(phase) / 4_294_967_296.0 * 2.0 * core::f64::consts::PI);
        worst = worst.max((f64::from(sin_turns(phase)) - exact).abs());
        let exact_c = libm::cos(f64::from(phase) / 4_294_967_296.0 * 2.0 * core::f64::consts::PI);
        worst = worst.max((f64::from(cos_turns(phase)) - exact_c).abs());
    }
    assert!(worst < 4e-7, "{worst}");
    assert_eq!(sin_turns(0), 0.0);
    assert_eq!(sin_turns(1 << 30), 1.0);
    assert_eq!(sin_turns(3 << 30), -1.0);
}

#[test]
fn constant_tone_has_the_right_frequency() {
    let symbols = [3u8; SYMBOL_COUNT];
    let mut out = vec![0.0; WAVEFORM_SAMPLES];
    Synth::new(&symbols, 1000.0, 1.0).unwrap().fill(&mut out);
    let seg = &out[12_000..24_000];
    let crossings = seg.windows(2).filter(|w| w[0] < 0.0 && w[1] >= 0.0).count();
    let expected = 1000.0 + 3.0 * TONE_SPACING_HZ; // 1018.75
    assert!((crossings as f32 - expected).abs() <= 1.0, "{crossings}");
}

#[test]
fn ramps_and_amplitude() {
    let symbols = [0u8; SYMBOL_COUNT];
    let mut out = vec![0.0; WAVEFORM_SAMPLES + 100];
    let p = Placement {
        base_hz: 1500.0,
        start: 50,
        amplitude: 0.5,
    };
    synthesize(&symbols, &p, &mut out).unwrap();
    assert!(out[..50].iter().all(|&x| x == 0.0));
    assert_eq!(out[50], 0.0); // sin(0) and zero envelope
    assert!(out[50..50 + 40].iter().all(|x| x.abs() < 0.1));
    let peak = out.iter().fold(0.0f32, |a, &x| a.max(x.abs()));
    assert!(peak <= 0.5 + 1e-6 && peak > 0.49);
    assert!(out[50 + WAVEFORM_SAMPLES..].iter().all(|&x| x == 0.0));
    assert!(out[50 + WAVEFORM_SAMPLES - 1].abs() < 1e-3);
    assert_eq!(envelope(0), 0.0);
    assert_eq!(envelope(RAMP_SAMPLES), 1.0);
    assert_eq!(envelope(WAVEFORM_SAMPLES - 1), 0.0);
}

fn symbols_of(text: &str) -> [u8; SYMBOL_COUNT] {
    encode(text, &mut NoHashes).unwrap().symbols
}

#[test]
fn blocks_of_any_size_give_the_same_samples() {
    let symbols = symbols_of("CQ K1ABC FN42");
    let mut whole = vec![0.0; WAVEFORM_SAMPLES];
    assert_eq!(
        Synth::new(&symbols, 1500.0, 0.7).unwrap().fill(&mut whole),
        WAVEFORM_SAMPLES
    );
    for block in [1usize, 7, 256, 1920, 4097] {
        let mut synth = Synth::new(&symbols, 1500.0, 0.7).unwrap();
        let mut got = Vec::with_capacity(WAVEFORM_SAMPLES);
        let mut buf = vec![0.0; block];
        loop {
            let n = synth.fill(&mut buf);
            got.extend_from_slice(&buf[..n]);
            if n < block {
                break;
            }
        }
        assert_eq!(got, whole, "block {block}");
        assert_eq!(synth.remaining(), 0);
        assert_eq!(synth.fill(&mut buf), 0);
    }
}

#[test]
fn phase_and_envelope_rebuild_the_samples() {
    let symbols = symbols_of("K1ABC W9XYZ -11");
    let mut samples = vec![0.0; 5000];
    Synth::new(&symbols, 812.5, 0.25)
        .unwrap()
        .fill(&mut samples);
    let mut phase = vec![0u32; 5000];
    let mut env = vec![0.0f32; 5000];
    let mut s = Synth::new(&symbols, 812.5, 0.25).unwrap();
    assert_eq!(s.fill_phase(&mut phase, &mut env), 5000);
    for k in 0..5000 {
        assert_eq!(samples[k], 0.25 * env[k] * sin_turns(phase[k]));
    }
}

#[test]
fn clipping_does_not_change_the_samples_that_remain() {
    let symbols = symbols_of("CQ K1ABC FN42");
    let mut full = vec![0.0; WAVEFORM_SAMPLES];
    let at = |start| Placement {
        base_hz: 1500.0,
        start,
        amplitude: 1.0,
    };
    synthesize(&symbols, &at(0), &mut full).unwrap();
    let mut part = vec![0.0; 1000];
    synthesize(&symbols, &at(-5000), &mut part).unwrap();
    assert_eq!(&full[5000..6000], &part[..]);
    // Extreme starts neither panic nor write.
    let mut buf = vec![0.0; 100];
    synthesize(&symbols, &at(i64::MIN), &mut buf).unwrap();
    synthesize(&symbols, &at(i64::MAX), &mut buf).unwrap();
    assert!(buf.iter().all(|&x| x == 0.0));
}

#[test]
fn rejects_bad_input() {
    let mut out = [0.0f32; 4];
    let p = Placement {
        base_hz: 1500.0,
        start: 0,
        amplitude: 1.0,
    };
    assert_eq!(
        synthesize(&[8; SYMBOL_COUNT], &p, &mut out),
        Err(Error::InvalidSymbol)
    );
    let top_ok = 6000.0 - 7.0 * TONE_SPACING_HZ - 0.01;
    assert!(Synth::new(&[0; SYMBOL_COUNT], top_ok, 1.0).is_ok());
    let too_high = 6000.0 - 7.0 * TONE_SPACING_HZ;
    assert_eq!(
        Synth::new(&[0; SYMBOL_COUNT], too_high, 1.0).err(),
        Some(Error::FrequencyOutOfRange)
    );
    assert_eq!(
        Synth::new(&[0; SYMBOL_COUNT], f32::NAN, 1.0).err(),
        Some(Error::FrequencyOutOfRange)
    );
    assert_eq!(
        Synth::new(&[0; SYMBOL_COUNT], 1500.0, f32::NAN).err(),
        Some(Error::NonFinite)
    );
    assert_eq!(
        Synth::new(&[0; SYMBOL_COUNT], 1500.0, f32::INFINITY).err(),
        Some(Error::NonFinite)
    );
    assert_eq!(Placement::slot(1500.0, f32::NAN), Err(Error::NonFinite));
    assert_eq!(
        Placement::slot(1500.0, f32::NEG_INFINITY),
        Err(Error::NonFinite)
    );
    assert_eq!(Placement::slot(1500.0, 0.0).unwrap().start, 6000);
    assert_eq!(Placement::slot(1500.0, -0.5).unwrap().start, 0);
    assert_eq!(Placement::slot(1500.0, 1e30).unwrap().start, i64::MAX);
    assert_eq!(round_to_i64(2.5), 3);
    assert_eq!(round_to_i64(-2.5), -3);
    assert_eq!(round_to_i64(-2.4), -2);
}

/// FNV-1a 64 over the little-endian bytes of each sample's bit pattern.
fn fnv1a(samples: &[f32]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for x in samples {
        for b in x.to_bits().to_le_bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    h
}

/// The determinism promise, pinned: these hashes must be identical on
/// every platform (CI runs them on Linux and Windows). A deliberate change
/// to the waveform changes them; update them in the same change.
const GOLDEN: &[(&str, f32, u64, u64)] = &[
    // (message, base Hz, waveform at amplitude 1, 15 s slot at 0.5 s)
    (
        "CQ K1ABC FN42",
        1500.0,
        0xef9e_fbd4_3cc7_d441,
        0x0b4f_21b0_71a8_13c1,
    ),
    (
        "K1ABC W9XYZ -11",
        812.5,
        0xf536_fbf2_9990_88fe,
        0xdaa9_b165_31e2_ef7e,
    ),
    (
        "<W9XYZ> PJ4/K1ABC RRR",
        2731.25,
        0x6b14_de3c_af74_bcd1,
        0xd678_fc46_8f91_ac51,
    ),
];

#[test]
fn golden_hashes() {
    let mut got = Vec::new();
    for &(msg, base, _, _) in GOLDEN {
        let symbols = symbols_of(msg);
        let mut wave = vec![0.0; WAVEFORM_SAMPLES];
        Synth::new(&symbols, base, 1.0).unwrap().fill(&mut wave);
        let mut slot = vec![0.0; SLOT_SAMPLES];
        synthesize(&symbols, &Placement::slot(base, 0.0).unwrap(), &mut slot).unwrap();
        let (w, s) = (fnv1a(&wave), fnv1a(&slot));
        std::println!("golden {msg:?} {base}: waveform {w:#018x} slot {s:#018x}");
        got.push((w, s));
    }
    let want: Vec<(u64, u64)> = GOLDEN.iter().map(|g| (g.2, g.3)).collect();
    assert_eq!(got, want);
}
