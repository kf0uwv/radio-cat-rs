fn tables_source() -> String {
    use std::fmt::Write;
    let mut s = String::new();
    s.push_str(LICENCE_HEADER);
    s.push_str(
        "// Generated by `cargo test -p cat-ft8 --lib print_decode_tables -- --ignored \
         --nocapture`;\n// checked bit-for-bit by `decode_tables_match_their_definitions`. Do not edit.\n\n",
    );
    let pairs = |s: &mut String, name: &str, doc: &str, v: &[[f32; 2]]| {
        writeln!(s, "{doc}").unwrap();
        writeln!(s, "#[rustfmt::skip]").unwrap();
        writeln!(s, "pub(crate) static {name}: [[f32; 2]; {}] = [", v.len()).unwrap();
        for chunk in v.chunks(3) {
            let line: Vec<String> = chunk
                .iter()
                .map(|p| std::format!("[{:?}, {:?}]", p[0], p[1]))
                .collect();
            writeln!(s, "    {},", line.join(", ")).unwrap();
        }
        writeln!(s, "];\n").unwrap();
    };
    pairs(
        &mut s,
        "TWIDDLES",
        "/// e^(−2πit/1920) as [cos, −sin], t = 0..1920.",
        &generate_twiddles(),
    );
    pairs(
        &mut s,
        "SPLIT_TWIDDLES",
        "/// e^(−2πik/3840) as [cos, −sin], k = 0..=960 (the real-split step).",
        &generate_split_twiddles(),
    );
    let hann = generate_hann_half();
    writeln!(
        s,
        "/// sin²(πn / 3840), n = 0..=1920: the first half of the periodic Hann window."
    )
    .unwrap();
    writeln!(s, "#[rustfmt::skip]").unwrap();
    writeln!(s, "pub(crate) static HANN_HALF: [f32; {}] = [", hann.len()).unwrap();
    for chunk in hann.chunks(6) {
        let line: Vec<String> = chunk.iter().map(|x| std::format!("{x:?}")).collect();
        writeln!(s, "    {},", line.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    s
}

