#[test]
fn decode_tables_match_their_definitions() {
    let bits2 = |v: &[[f32; 2]]| {
        v.iter()
            .map(|p| (p[0].to_bits(), p[1].to_bits()))
            .collect::<Vec<_>>()
    };
    assert_eq!(bits2(&TWIDDLES), bits2(&generate_twiddles()));
    assert_eq!(bits2(&SPLIT_TWIDDLES), bits2(&generate_split_twiddles()));
    let bits = |v: &[f32]| v.iter().map(|x| x.to_bits()).collect::<Vec<_>>();
    assert_eq!(bits(&HANN_HALF), bits(&generate_hann_half()));
}

/// The recursive definition of the input order: the top-level stage splits
/// the sequence into its `r` interleaved subsequences, stored in blocks.
fn digit_rev_reference(list: &[usize], radices_top_down: &[usize]) -> Vec<usize> {
    let Some((&r, rest)) = radices_top_down.split_first() else {
        return list.to_vec();
    };
    let mut out = Vec::new();
    for m in 0..r {
        let sub: Vec<usize> = list.iter().copied().skip(m).step_by(r).collect();
        out.extend(digit_rev_reference(&sub, rest));
    }
    out
}

#[test]
fn digit_reversal_matches_its_definition_and_is_a_permutation() {
    let top_down: Vec<usize> = STAGES.iter().rev().copied().collect();
    let want = digit_rev_reference(&(0..N).collect::<Vec<_>>(), &top_down);
    let got: Vec<usize> = DIGIT_REV.iter().map(|&x| usize::from(x)).collect();
    assert_eq!(got, want);
    let mut seen = std::vec![false; N];
    for &x in &got {
        assert!(!seen[x]);
        seen[x] = true;
    }
}

/// xorshift64 → uniform f32 in [−1, 1).
fn noise(seed: &mut u64) -> f32 {
    *seed ^= *seed << 13;
    *seed ^= *seed >> 7;
    *seed ^= *seed << 17;
    ((*seed >> 40) as f32 / (1u64 << 23) as f32) - 1.0
}

/// Complex DFT in f64 with an exact-angle table (tests only).
fn dft_f64(x: &[(f64, f64)]) -> Vec<(f64, f64)> {
    let n = x.len();
    let table: Vec<(f64, f64)> = (0..n)
        .map(|t| {
            let a = 2.0 * core::f64::consts::PI * t as f64 / n as f64;
            (libm::cos(a), -libm::sin(a))
        })
        .collect();
    (0..n)
        .map(|k| {
            let (mut re, mut im) = (0.0, 0.0);
            for (j, &(xr, xi)) in x.iter().enumerate() {
                let (c, s) = table[(j * k) % n];
                re += xr * c - xi * s;
                im += xr * s + xi * c;
            }
            (re, im)
        })
        .collect()
}

#[test]
fn complex_fft_matches_an_f64_dft() {
    let mut seed = 0x1234_5678_9abc_def1u64;
    let input: Vec<Complex> = (0..N)
        .map(|_| Complex {
            re: noise(&mut seed),
            im: noise(&mut seed),
        })
        .collect();
    let mut buf = [Complex::ZERO; N];
    for (p, slot) in buf.iter_mut().enumerate() {
        *slot = input[usize::from(DIGIT_REV[p])];
    }
    fft(&mut buf);
    let want = dft_f64(
        &input
            .iter()
            .map(|c| (f64::from(c.re), f64::from(c.im)))
            .collect::<Vec<_>>(),
    );
    let peak = want
        .iter()
        .map(|&(r, i)| (r * r + i * i).sqrt())
        .fold(0.0, f64::max);
    let worst = buf
        .iter()
        .zip(&want)
        .map(|(g, &(r, i))| ((f64::from(g.re) - r).powi(2) + (f64::from(g.im) - i).powi(2)).sqrt())
        .fold(0.0, f64::max);
    std::println!(
        "complex FFT: max error {worst:.3e}, relative to peak {:.3e}",
        worst / peak
    );
    assert!(worst / peak < 2.0e-6, "{}", worst / peak);
}

#[test]
fn real_spectrum_matches_an_f64_dft_of_the_windowed_samples() {
    let mut seed = 0x0fed_cba9_8765_4321u64;
    let mut samples = [0.0f32; WINDOW];
    for s in samples.iter_mut() {
        *s = noise(&mut seed);
    }
    let mut buf = FftBuffer::new();
    let mut ours = std::vec![0.0f32; BINS];
    power_spectrum(&samples, &mut buf, 0, &mut ours);
    // Reference: the window from its definition in f64, then a DFT.
    let windowed: Vec<(f64, f64)> = samples
        .iter()
        .enumerate()
        .map(|(n, &x)| {
            let w = libm::sin(core::f64::consts::PI * n as f64 / WINDOW as f64);
            (f64::from(x) * w * w, 0.0)
        })
        .collect();
    let full = dft_f64(&windowed);
    let want: Vec<f64> = full[..BINS]
        .iter()
        .map(|&(r, i)| (r * r + i * i) / 921_600.0)
        .collect();
    let peak = want.iter().copied().fold(0.0, f64::max);
    let mut worst_abs = 0.0f64;
    let mut worst_db = 0.0f64;
    for (g, &w) in ours.iter().zip(&want) {
        worst_abs = worst_abs.max((f64::from(*g) - w).abs());
        if w > peak * 1e-6 {
            worst_db = worst_db.max((10.0 * libm::log10(f64::from(*g) / w)).abs());
        }
    }
    std::println!(
        "real spectrum: max power error {:.3e} of peak; max {:.2e} dB in bins within 60 dB of peak",
        worst_abs / peak,
        worst_db
    );
    assert!(worst_abs / peak < 1.0e-5);
    assert!(worst_db < 1.0e-3);
}

#[test]
fn a_full_scale_sine_centred_in_a_bin_reads_one() {
    let mut samples = [0.0f32; WINDOW];
    for (n, s) in samples.iter_mut().enumerate() {
        // 1 500 Hz = bin 480 exactly.
        let a = 2.0 * core::f64::consts::PI * 480.0 * n as f64 / WINDOW as f64;
        *s = libm::cos(a) as f32;
    }
    let mut buf = FftBuffer::new();
    let mut out = [0.0f32; 5];
    power_spectrum(&samples, &mut buf, 478, &mut out);
    assert!((out[2] - 1.0).abs() < 1.0e-4, "{out:?}");
    assert!(
        (out[1] - 0.25).abs() < 1.0e-4 && (out[3] - 0.25).abs() < 1.0e-4,
        "{out:?}"
    );
    assert!(out[0] < 1.0e-8 && out[4] < 1.0e-8, "{out:?}");
}

