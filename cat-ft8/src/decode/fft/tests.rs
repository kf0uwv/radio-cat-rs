/// e^(−2πit/1920) as (cos, −sin), computed in f64 and rounded.
fn generate_twiddles() -> Vec<[f32; 2]> {
    (0..N)
        .map(|t| {
            let a = 2.0 * core::f64::consts::PI * t as f64 / N as f64;
            [libm::cos(a) as f32, -libm::sin(a) as f32]
        })
        .collect()
}

/// e^(−2πik/3840) for k = 0..=960.
fn generate_split_twiddles() -> Vec<[f32; 2]> {
    (0..=960)
        .map(|k| {
            let a = 2.0 * core::f64::consts::PI * k as f64 / WINDOW as f64;
            [libm::cos(a) as f32, -libm::sin(a) as f32]
        })
        .collect()
}

/// Linear power of each 8-bit level: 10^((v − 255) / 20) (0.5 dB steps,
/// 1.0 at the top level).
fn generate_level_power() -> Vec<f32> {
    (0..256)
        .map(|v| libm::pow(10.0, (f64::from(v) - 255.0) / 20.0) as f32)
        .collect()
}

/// sin²(πn / 3840) for n = 0..=1920 (the periodic Hann window's first
/// half; the rest mirrors).
fn generate_hann_half() -> Vec<f32> {
    (0..=WINDOW / 2)
        .map(|n| {
            let s = libm::sin(core::f64::consts::PI * n as f64 / WINDOW as f64);
            (s * s) as f32
        })
        .collect()
}

